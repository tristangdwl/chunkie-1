function sixth = green_helmsq_sixth(k,src,targ)
%CHNK.FLEX2D.GREEN_SIXTH evaluate the sixth derivatives of the Helmholtz
%squaredgreen's function for the given sources and targets

[~,ns] = size(src);
[~,nt] = size(targ);

xs = repmat(src(1,:),nt,1);
ys = repmat(src(2,:),nt,1);

xt = repmat(targ(1,:).',1,ns);
yt = repmat(targ(2,:).',1,ns);

rx = xt-xs;
ry = yt-ys;

rx2 = rx.*rx;
ry2 = ry.*ry;

r2 = rx2+ry2;

r = sqrt(r2);

[m,n] = size(xs);

h0 = besselh(0,1,k*r);
h1 = besselh(1,1,k*r);
sixth = zeros(m,n,7);
sixth(:,:,1) = (1i*(-1/8)).*k.^3.*(3.*h0.*k.*r.^(-8).*(k.^2.*rx.^8+45.* ...
  rx.^2.*ry.^4+(-5).*ry.^6+5.*rx.^4.*ry.^2.*((-3)+k.^2.*ry.^2)+ ...
  rx.^6.*((-1)+6.*k.^2.*ry.^2))+(-1).*h1.*r.^(-9).*(k.^4.*rx.^10+( ...
  -30).*ry.^6+(-45).*rx.^2.*ry.^4.*((-6)+k.^2.*ry.^2)+(-15).*rx.^4.* ...
  ry.^2.*(6+k.^2.*ry.^2)+k.^2.*rx.^8.*(3+2.*k.^2.*ry.^2)+rx.^6.*(( ...
  -6)+33.*k.^2.*ry.^2+k.^4.*ry.^4)));
sixth(:,:,2) = (1i*(1/8)).*k.^3.*rx.*ry.*(2.*h0.*k.*(rx.^2+ry.^2).^(-4).*( ...
  rx.^4.*((-6)+k.^2.*rx.^2)+(-4).*rx.^2.*((-15)+k.^2.*rx.^2).*ry.^2+ ...
  (-5).*(6+k.^2.*rx.^2).*ry.^4)+h1.*(rx.^2+ry.^2).^(-9/2).*(k.^4.* ...
  rx.^8+(-15).*ry.^4.*((-8)+k.^2.*ry.^2)+k.^2.*rx.^6.*((-7)+2.* ...
  k.^2.*ry.^2)+5.*rx.^2.*ry.^2.*((-48)+7.*k.^2.*ry.^2)+rx.^4.*(24+ ...
  43.*k.^2.*ry.^2+k.^4.*ry.^4)));
sixth(:,:,3) = (1i*(-1/8)).*k.^3.*((-1).*h1.*r.^(-9).*(2.*rx.^6.*((-3)+ ...
  k.^2.*rx.^2)+rx.^4.*(150+(-29).*k.^2.*rx.^2+k.^4.*rx.^4).*ry.^2+ ...
  rx.^2.*((-210)+5.*k.^2.*rx.^2+2.*k.^4.*rx.^4).*ry.^4+(18+33.* ...
  k.^2.*rx.^2+k.^4.*rx.^4).*ry.^6+(-3).*k.^2.*ry.^8)+h0.*k.*r.^(-8) ...
  .*(k.^2.*rx.^8+9.*ry.^6+rx.^4.*ry.^2.*(75+k.^2.*ry.^2)+3.*rx.^2.* ...
  ry.^4.*((-35)+2.*k.^2.*ry.^2)+(-1).*rx.^6.*(3+4.*k.^2.*ry.^2)));
sixth(:,:,4) = (1i*(-1/8)).*k.^3.*rx.*ry.*(3.*h0.*k.*r.^(-8).*(k.^2.*rx.^6+ ...
  rx.^2.*ry.^2.*(40+(-1).*k.^2.*ry.^2)+ry.^4.*((-12)+k.^2.*ry.^2)+( ...
  -1).*rx.^4.*(12+k.^2.*ry.^2))+(-1).*h1.*r.^(-9).*(k.^2.*rx.^6.*( ...
  15+k.^2.*ry.^2)+3.*ry.^4.*((-24)+5.*k.^2.*ry.^2)+rx.^2.*ry.^2.*( ...
  240+(-27).*k.^2.*ry.^2+k.^4.*ry.^4)+rx.^4.*((-72)+(-27).*k.^2.* ...
  ry.^2+2.*k.^4.*ry.^4)));
sixth(:,:,5) = (1i*(-1/8)).*k.^3.*(h0.*k.*r.^(-8).*(9.*rx.^6+3.*rx.^4.*(( ...
  -35)+2.*k.^2.*rx.^2).*ry.^2+rx.^2.*(75+k.^2.*rx.^2).*ry.^4+(-1).*( ...
  3+4.*k.^2.*rx.^2).*ry.^6+k.^2.*ry.^8)+h1.*r.^(-9).*(3.*k.^2.* ...
  rx.^8+6.*ry.^6+(-2).*k.^2.*ry.^8+rx.^4.*ry.^2.*(210+(-5).*k.^2.* ...
  ry.^2+(-2).*k.^4.*ry.^4)+(-1).*rx.^2.*ry.^4.*(150+(-29).*k.^2.* ...
  ry.^2+k.^4.*ry.^4)+(-1).*rx.^6.*(18+33.*k.^2.*ry.^2+k.^4.*ry.^4))) ...
  ;
sixth(:,:,6) = (1i*(-1/8)).*k.^3.*rx.*ry.*(h1.*r.^(-9).*(15.*rx.^4.*((-8)+ ...
  k.^2.*rx.^2)+5.*rx.^2.*(48+(-7).*k.^2.*rx.^2).*ry.^2+(-1).*(24+ ...
  43.*k.^2.*rx.^2+k.^4.*rx.^4).*ry.^4+k.^2.*(7+(-2).*k.^2.*rx.^2).* ...
  ry.^6+(-1).*k.^4.*ry.^8)+2.*h0.*k.*r.^(-8).*(6.*ry.^4+(-1).*k.^2.* ...
  ry.^6+4.*rx.^2.*ry.^2.*((-15)+k.^2.*ry.^2)+5.*rx.^4.*(6+k.^2.* ...
  ry.^2)));
sixth(:,:,7) = (1i*(1/8)).*k.^3.*(h1.*r.^(-9).*((-30).*rx.^6+(-45).*rx.^4.* ...
  ((-6)+k.^2.*rx.^2).*ry.^2+(-15).*rx.^2.*(6+k.^2.*rx.^2).*ry.^4+(( ...
  -6)+33.*k.^2.*rx.^2+k.^4.*rx.^4).*ry.^6+k.^2.*(3+2.*k.^2.*rx.^2).* ...
  ry.^8+k.^4.*ry.^10)+(-3).*h0.*k.*r.^(-8).*((-5).*rx.^6+(-1).* ...
  ry.^6+k.^2.*ry.^8+5.*rx.^4.*ry.^2.*(9+k.^2.*ry.^2)+3.*rx.^2.* ...
  ry.^4.*((-5)+2.*k.^2.*ry.^2))); 

% sixth  = 0.25*1i*sixth;
